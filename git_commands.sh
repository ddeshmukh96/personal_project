# To check current branch : git branch 
# To add files to staging : git add . ( dot if you want to add all the modified files OR file names separated by spaces)
# To check modified files : git status ( gives all the modified files in the current branch )
# To commit staged files : git commit -m "Your message"
# To push the commit : git push (Now you will push your changes to the repository)

